"""Exercise an installed wheel outside its checkout, with an optional real browser."""

import argparse
import csv
import json
import os
from pathlib import Path
import socket
import subprocess
import sys
import sysconfig
import tempfile
import time
import urllib.request

from fastapi.testclient import TestClient
import support_ticket_ai
from support_ticket_ai.api import create_app
from support_ticket_ai.data import load_tickets
from support_ticket_ai.freeze_review import verify_manifest
from support_ticket_ai.predict import TicketPredictor
from support_ticket_ai.prepare import prepare
from support_ticket_ai.resources import data_path, report_path
from support_ticket_ai.train import run_training


def fixture(root: Path) -> Path:
    source = root / 'source.csv'
    with source.open('w', encoding='utf-8', newline='') as handle:
        writer = csv.writer(handle)
        writer.writerow(['instruction', 'category'])
        for label, text in [('ACCOUNT', 'password reset account login'), ('PAYMENT', 'payment card bank charge')]:
            for number in range(30):
                writer.writerow([f'{text} request {number}', label])
    license_file = root / 'license.txt'
    license_file.write_text('Synthetic smoke-test fixture, generated by the project.')
    prepared, model = root / 'prepared', root / 'model'
    prepare(source, prepared, 'a' * 40, license_file)
    (prepared / 'test.csv').unlink()  # No test file is needed for the fixture.
    report = run_training(prepared, model)
    (model / 'abstention_policy.json').write_text(json.dumps({
        'policy_version': 1, 'kind': 'experimental_max_probability',
        'model_sha256': report['model_sha256'], 'threshold': .7, 'human_review_required': True,
    }))
    predictor = TicketPredictor(model)
    assert predictor.predict('password reset account login')['suggested_category'] == 'ACCOUNT'
    assert predictor.predict('zzzxxyy qqqvvv')['decision'] == 'abstain'
    return model


def api_checks(model: Path):
    assert len(load_tickets(data_path('sample_tickets.csv'))) == 12
    assert verify_manifest(data_path('ambiguity_review_cases.csv'), data_path('ambiguity_review_manifest.json'))['rows'] == 72
    for name in ('development_challenge.csv', 'robustness_probes.csv', 'scope_training_negatives.csv',
                 'review_pilot.csv', 'ambiguity_review_cases.csv', 'ambiguity_review_manifest.json'):
        assert data_path(name).is_file(), name
    assert json.loads(report_path('semantic_experiment.json').read_text())['test_evaluated'] is False
    with TestClient(create_app(model)) as client:
        assert client.get('/healthz').status_code == 200
        assert client.get('/readyz').status_code == 200
        assert 'ticket-form' in client.get('/').text
        for asset in ('styles.css', 'app.js', 'result-view.js', 'workspace.js', 'breakdown.js'):
            assert client.get('/assets/' + asset).status_code == 200
        response = client.post('/predict', json={'text': 'password reset account login'})
        assert response.status_code == 200
        assert response.json()['suggested_category'] == 'ACCOUNT'
        assert response.json()['requires_human_review'] is True
        assert client.post('/predict', json={'text': 'zzzxxyy qqqvvv'}).json()['decision'] == 'abstain'
        assert client.post('/predict', json={'text': ''}).status_code == 422
    with TestClient(create_app(model / 'absent')) as client:
        assert client.get('/').status_code == 200
        assert client.get('/readyz').status_code == 503
        assert client.post('/predict', json={'text': 'account help'}).status_code == 503


def browser_checks(model: Path, artifacts: Path, executable: str | None):
    from playwright.sync_api import expect, sync_playwright
    with socket.socket() as probe:
        probe.bind(('127.0.0.1', 0))
        port = probe.getsockname()[1]
    artifacts.mkdir(parents=True, exist_ok=True)
    base = f'http://127.0.0.1:{port}'
    with (artifacts / 'server.log').open('w') as log:
        server = subprocess.Popen([sys.executable, '-m', 'uvicorn', 'support_ticket_ai.api:app',
                                   '--host', '127.0.0.1', '--port', str(port)],
                                  env=dict(os.environ, SUPPORT_TICKET_MODEL_DIR=str(model), SUPPORT_TICKET_REQUESTS_DB=str(model.parent / "requests.sqlite3")),
                                  stdout=log, stderr=subprocess.STDOUT)
        try:
            deadline = time.monotonic() + 20
            while True:
                try:
                    urllib.request.urlopen(base + '/readyz', timeout=1).close()
                    break
                except OSError:
                    if server.poll() is not None or time.monotonic() >= deadline:
                        raise RuntimeError('Fixture API failed to become ready; see server.log')
                    time.sleep(.1)
            with sync_playwright() as p:
                options = {'headless': True}
                if executable:
                    options.update(executable_path=executable, args=['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu', '--no-zygote'])
                browser = p.chromium.launch(**options)
                context = browser.new_context()
                context.tracing.start(screenshots=True, snapshots=True, sources=True)
                page = context.new_page()
                errors = []
                page.on('pageerror', lambda error: errors.append(str(error)))
                try:
                    for width, height in ((1440, 1000), (390, 844)):
                        page.set_viewport_size({'width': width, 'height': height})
                        page.goto(base)
                        expect(page.locator('#service-label')).to_have_text('Model ready')
                        expect(page.locator('#submit')).to_be_disabled()
                        expect(page.locator('#model-mode')).to_have_value('word')
                        expect(page.locator('#semantic-option')).to_be_disabled()
                        page.locator('#ticket').fill('password reset account login')
                        page.get_by_role('button', name='Suggest category').click()
                        expect(page.locator('#category')).to_have_text('Account')
                        assert json.loads(page.locator('#json-response').text_content())['requires_human_review'] is True
                        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Horizontal overflow'
                        page.screenshot(path=str(artifacts / f'installed-{width}.png'), full_page=True)
                        page.locator('#ticket').fill('zzzxxyy qqqvvv')
                        expect(page.locator('#result-success')).to_be_hidden()
                        page.get_by_role('button', name='Suggest category').click()
                        expect(page.locator('#category')).to_have_text('Category withheld')
                        assert json.loads(page.locator('#json-response').text_content())['suggested_category'] is None
                        page.locator('#ticket').fill('x' * 2001)
                        expect(page.locator('#submit')).to_be_disabled()
                    page.locator('#ticket').fill('password reset account login')
                    page.route('**/predict', lambda route: route.abort())
                    page.get_by_role('button', name='Suggest category').click()
                    expect(page.locator('#form-error')).to_be_visible()
                    page.unroute('**/predict')
                    page.locator('#ticket').fill('password reset account login again')
                    page.get_by_role('button', name='Suggest category').click()
                    expect(page.locator('#category')).to_have_text('Account')
                    page.route('**/readyz*', lambda route: route.fulfill(status=503, content_type='application/json', body='{}'))
                    page.reload()
                    expect(page.locator('#service-label')).to_have_text('Model unavailable')
                    expect(page.locator('#submit')).to_be_disabled()
                    page.unroute('**/readyz*')
                    page.locator('#retry').click()
                    expect(page.locator('#service-label')).to_have_text('Model ready')
                    assert not errors, errors
                except Exception:
                    page.screenshot(path=str(artifacts / 'failure.png'), full_page=True)
                    raise
                finally:
                    context.tracing.stop(path=str(artifacts / 'trace.zip'))
                    browser.close()
        finally:
            server.terminate()
            try:
                server.wait(timeout=10)
            except subprocess.TimeoutExpired:
                server.kill()
                server.wait(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--browser', action='store_true')
    parser.add_argument('--browser-executable', help='Optional existing Chromium binary for local verification')
    parser.add_argument('--artifacts', type=Path, default=Path.cwd() / 'install-check-artifacts')
    args = parser.parse_args()
    checkout = Path(__file__).resolve().parents[1]
    installed = Path(support_ticket_ai.__file__).resolve()
    assert not installed.is_relative_to(checkout), f'Imported source checkout instead of installed wheel: {installed}'
    scripts_dir = Path(sysconfig.get_path('scripts'))
    suffix = '.exe' if os.name == 'nt' else ''
    validated = subprocess.run([str(scripts_dir / ('support-ticket-ai' + suffix)), str(data_path('sample_tickets.csv'))],
                               capture_output=True, text=True, check=True)
    assert 'Validated 12 tickets' in validated.stdout
    for command in ('support-ticket-demo', 'support-ticket-serve', 'support-ticket-predict', 'support-ticket-semantic'):
        subprocess.run([str(scripts_dir / (command + suffix)), '--help'], capture_output=True, text=True, check=True)
    with tempfile.TemporaryDirectory(prefix='ticket-installed-') as directory:
        model = fixture(Path(directory))
        api_checks(model)
        if args.browser:
            browser_checks(model, args.artifacts.resolve(), args.browser_executable)
    print(json.dumps({'installed_package': str(installed), 'api_assets_prediction_checks': 'passed',
                      'browser_checks': 'passed' if args.browser else 'not_requested',
                      'fixture': 'generated synthetic data; no user annotations or external dataset'}))


if __name__ == '__main__':
    main()
